  function resolve(source, key) {
    return key.split('.').reduce(function (current, part) {
      if (current && typeof current === 'object' && part in current) {
        return current[part];
      }
      return undefined;
    }, source);
  }

  function detectLanguage() {
    try {
      var saved = localStorage.getItem('trailReplayLang');
      if (saved && saved in translations) {
        return saved;
      }
    } catch {}

    var browser = navigator.language ? navigator.language.slice(0, 2) : 'en';
    return browser in translations ? browser : 'en';
  }

  var lang = detectLanguage();
  var page = document.documentElement.dataset.page;
  var pageTranslations = translations[lang] && translations[lang][page];

  if (!pageTranslations) {
    return;
  }

  document.documentElement.lang = lang;
  document.title = pageTranslations.documentTitle;

  document.querySelectorAll('[data-i18n]').forEach(function (node) {
    var key = node.getAttribute('data-i18n');
    var value = key ? resolve(pageTranslations, key) : undefined;

    if (typeof value === 'string') {
      node.textContent = value;
    }
  });
